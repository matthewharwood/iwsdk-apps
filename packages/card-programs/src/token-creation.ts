function definitionFor(recipe: FixedTokenSpellSource): CardDefinition {
  const template = FIXED_TOKEN_TEMPLATES[recipe.templateId];
  if (!template) throw new Error("Pinned token template is missing");
  return CardDefinition.parse({
    id: `oracle:${recipe.identity}`,
    oracleId: recipe.identity,
    sourceVersion: recipe.sourceVersion,
    name: recipe.name,
    typeLine: recipe.typeLine,
    types: [recipe.typeLine],
    subtypes: [],
    supertypes: [],
    colors: recipe.colors,
    colorIdentity: recipe.colorIdentity,
    manaCost: recipe.cost,
    manaValue: recipe.manaValue,
    power: null,
    toughness: null,
    keywords: [],
    manaAbilities: [],
    oracleText: recipe.oracleText,
    commanderEligible: false,
    deckLimit: 1,
    obligations: [
      ...FIXED_TOKEN_RULES,
      ...template.characteristics.keywords.map((keyword) => KEYWORD_RULES[keyword]),
    ].map((rule) => `rule:${rule}`),
    implementationRevision: FIXED_TOKEN_VERSION,
    spellProgram: SpellProgram.parse({
      schema: "commander-spell/1",
      target: null,
      effects: [
        {
          kind: "create-token",
          recipient: "controller",
          count: recipe.count,
          templateId: recipe.templateId,
        },
      ],
    }),
  });
}
export function bindFixedTokenSpell(card: CatalogCard): CardDefinition | null {
  const recipe = FIXED_TOKEN_SPELLS.find((row) => row.identity === card.identity);
  if (!recipe) return null;
  const o = card.oracle;
  if (
    !card.eligibility.some((row) => row.role === "main-deck" && row.status === "candidate") ||
    card.versionHash !== recipe.sourceVersion ||
    card.sourceOrdinal !== recipe.sourceOrdinal ||
    card.sourceArchiveHash !== FIXED_TOKEN_ARCHIVE ||
    card.bundleHash !== FIXED_TOKEN_SOURCE_BUNDLE ||
    o.oracle_id !== recipe.identity ||
    o.name !== recipe.name ||
    o.layout !== "normal" ||
    o.card_faces !== undefined ||
    o.oracle_text !== recipe.oracleText ||
    o.type_line !== recipe.typeLine ||
    o.mana_cost !== recipe.manaCost ||
    o.cmc !== recipe.manaValue ||
    o.power !== undefined ||
    o.toughness !== undefined ||
    canonicalJson(o.colors ?? []) !== canonicalJson(recipe.colors) ||
    canonicalJson(o.color_identity) !== canonicalJson(recipe.colorIdentity) ||
    canonicalJson(o.keywords ?? []) !== canonicalJson([]) ||
    canonicalJson(o.all_parts ?? []) !== canonicalJson(recipe.relatedParts)
  )
    return null;
  return definitionFor(recipe);
}
/** Reconstruct the complete producer before its exact auxiliary dependency can be declared. */
export function reviewedFixedTokenDefinition(definition: CardDefinition): boolean {
  const recipe = FIXED_TOKEN_SPELLS.find((row) => row.identity === definition.oracleId);
  return recipe !== undefined && canonicalJson(definitionFor(recipe)) === canonicalJson(definition);
}
/** Only this finite source-derived template dictionary is recognized; hashing arbitrary shapes is insufficient. */
export function reviewedTokenTemplate(template: TokenTemplate): boolean {
  const expected = FIXED_TOKEN_TEMPLATES[template.id];
  return expected !== undefined && canonicalJson(expected) === canonicalJson(template);
}
